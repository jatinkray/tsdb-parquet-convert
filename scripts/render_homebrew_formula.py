#!/usr/bin/env python3
"""Render a Homebrew formula for a published release from its SHA256SUMS.

Usage:
    python3 scripts/render_homebrew_formula.py <version> <SHA256SUMS> <release-base-url>

`<release-base-url>` is the directory that holds the assets, for example
`https://github.com/owner/repo/releases/download`. The checksum file is the one
attached to that release; nothing is downloaded here.
"""

from __future__ import annotations

import sys
from pathlib import Path

# Homebrew selector -> release asset target triple.
PLATFORMS = {
    "on_macos": {
        "on_arm": "aarch64-apple-darwin",
        "on_intel": "x86_64-apple-darwin",
    },
    "on_linux": {
        "on_arm": "aarch64-unknown-linux-musl",
        "on_intel": "x86_64-unknown-linux-musl",
    },
}


def parse_checksums(text: str) -> dict[str, str]:
    checksums: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) < 2:
            raise SystemExit(f"malformed checksum line: {line!r}")
        digest, name = parts[0], parts[-1].lstrip("*")
        checksums[name] = digest
    return checksums


def homepage(base_url: str) -> str:
    marker = "/releases/download"
    return base_url[: -len(marker)] if base_url.endswith(marker) else base_url


def render(version: str, checksums: dict[str, str], base_url: str) -> str:
    lines = [
        f"# Generated by scripts/render_homebrew_formula.py for {version}",
        "class Tsdb2parqtel < Formula",
        '  desc "Convert Prometheus/Thanos TSDB blocks to Parquet"',
        f'  homepage "{homepage(base_url)}"',
        f'  version "{version}"',
        '  license "MIT"',
        "",
    ]
    for os_selector, arches in PLATFORMS.items():
        lines.append(f"  {os_selector} do")
        for arch_selector, target in arches.items():
            asset = f"tsdb2parqtel-{version}-{target}.tar.gz"
            if asset not in checksums:
                raise SystemExit(f"missing checksum for {asset}")
            lines += [
                f"    {arch_selector} do",
                f'      url "{base_url}/v{version}/{asset}"',
                f'      sha256 "{checksums[asset]}"',
                "    end",
            ]
        lines += ["  end", ""]
    lines += [
        "  def install",
        '    bin.install "tsdb2parqtel"',
        "  end",
        "",
        "  test do",
        '    assert_match version.to_s, shell_output("#{bin}/tsdb2parqtel --version")',
        "  end",
        "end",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    version, checksum_path, base_url = argv[1], Path(argv[2]), argv[3].rstrip("/")
    checksums = parse_checksums(checksum_path.read_text())
    sys.stdout.write(render(version, checksums, base_url))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
